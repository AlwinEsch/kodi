    def __gni_to_cmake__(self, gni, cmake, prepend = ""):
        """
        Convert GNI to CMake files
        """

        options = self.settings.options

        Log.PrintBegin(" - Convert: ")
        Log.PrintFollow("/src/{} to /cmake/{}".format(gni, cmake))

        src_gn_file = os.path.join(options.sourcepath, "src", gni)
        dst_file = os.path.join(options.sourcepath, "cmake", cmake)

        if not os.path.exists(src_gn_file):
            Log.PrintResult(Result.FAILURE)
            Log.PrintFatal("File \"{}\" not present".format(src_gn_file))
            return False

        if os.path.exists(dst_file) and not options.force:
            Log.PrintResult(Result.ALREADY_DONE)
            return True

        values = []
        #values.append("echo") # For local test purposes, used to see given command without call
        values.append("python")
        values.append(self.settings.used_gni_to_cmake_path)
        values.append(src_gn_file)
        values.append(dst_file)
        if prepend:
            values.append("--prepend")
            values.append("src/{}/".format(prepend))

        retcode = subprocess.call(values)
        if retcode != 0:
            Log.PrintResult(Result.FAILURE)
            Log.PrintFatal("gni-to-cmake.py failed to convert")
            return False

        Log.PrintResult(Result.OK)
        return True


    def __copy_own_cmake_file__(self):
        """
        Copy own cmake files present on ./kodi-dev-kit/tools/code-generator/src/depends_angle/add_to_angle_source/cmake-buildsystem
        to our used angle.
        """

        defaults = self.settings.defaults # Reduce line lengths
        options = self.settings.options

        base_path = os.path.join(defaults.SCRIPT_DIRECTORY, "add_to_angle_source", "cmake-buildsystem")
        target_path = options.sourcepath

        def _copyfunction(src, dst):
            file = src.replace(base_path, '')
            dstfile  = dst.replace(target_path + "/", '')
            Log.PrintBegin(" - Copy: ")
            Log.PrintFollow(".{} to angle/{}".format(file, dstfile))
            if os.path.exists(dst) and not options.force:
                Log.PrintResult(Result.ALREADY_DONE)
                return

            shutil.copy2(src, dst)
            Log.PrintResult(Result.OK)
            return

        Log.PrintBegin("Copy in kodi-dev-kit included CMake files to Angle source")
        Log.PrintResult(Result.SEE_BELOW)

        shutil.copytree(base_path, target_path, copy_function=_copyfunction, dirs_exist_ok=True)

        return True
